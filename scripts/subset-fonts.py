#!/usr/bin/env python3
"""重建本地书法字体分片，依赖 fonttools[woff]==4.62.1。

运行 python3 scripts/subset-fonts.py；完整原字体与 OFL 保留在 public/fonts，
作为可重复生成的来源。前台无需外部字体服务、运行时生成或完整字体回退。
"""

from collections import defaultdict
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path

import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/fonts/ma-shan-zheng.woff2"
OUTPUT = ROOT / "public/fonts/calligraphy"
CSS = ROOT / "src/app/calligraphy.css"
REPORT = ROOT / "docs/qa/font-optimization-2026-11-07.json"
TITLE = "让热爱，有处可达。"
# 后台和登录页的固定题字单独分片；未来修改的标题仍由其余 Unicode 分片覆盖。
THEME_TEXT = "整理你的山海书简让这里更像你好为天地落款久不见"
FAMILY = "Nav Palace Calligraphy"


def unicode_ranges(codepoints):
    """只输出实际连续的字符范围，避免范围包含并不存在的码点。"""
    points = sorted(codepoints)
    groups = []
    start = end = points[0]
    for point in points[1:]:
        if point == end + 1:
            end = point
        else:
            groups.append((start, end))
            start = end = point
    groups.append((start, end))
    return ", ".join(
        f"U+{start:04X}" if start == end else f"U+{start:04X}-{end:04X}"
        for start, end in groups
    )


def glyph_signature(font, glyph_name):
    # 复合字形也展开比对，确保轮廓和度量保持一致。
    coordinates, endpoints, flags = font["glyf"][glyph_name].getCoordinates(font["glyf"])
    return (list(coordinates), list(endpoints), list(flags), font["hmtx"][glyph_name])


def main():
    source = TTFont(SOURCE, recalcTimestamp=False)
    original_cmap = source.getBestCmap()
    all_points = set(original_cmap)
    # 完整 WOFF2 只解码一次，后续复用内存 sfnt，避免每个分片重建全部字形。
    source.flavor = None
    sfnt = BytesIO()
    source.save(sfnt, reorderTables=True)
    sfnt_data = sfnt.getvalue()
    remaining = all_points.copy()
    groups = []
    for label, text in (("headline", TITLE), ("theme", THEME_TEXT)):
        points = remaining & {ord(character) for character in text}
        if points:
            groups.append((label, points))
            remaining -= points
    blocks = defaultdict(set)
    for point in remaining:
        blocks[point // 256].add(point)
    groups.extend((f"u{block * 256:04x}", blocks[block]) for block in sorted(blocks))

    OUTPUT.mkdir(parents=True, exist_ok=True)
    css = [
        "/* Generated by scripts/subset-fonts.py; do not edit manually.",
        " * Ma Shan Zheng, copyright 2018 The Ma Shan Zheng Project Authors.",
        " * SIL OFL 1.1: /fonts/OFL-MaShanZheng.txt. Original font retained as source.",
        " * Exact disjoint Unicode ranges preserve all original mapped characters.",
        " */",
        ':root { --font-calligraphy: "Nav Palace Calligraphy", "Songti SC", serif; }',
        "",
    ]
    records = []
    seen = set()
    outlines_checked = 0
    for label, points in groups:
        font = TTFont(BytesIO(sfnt_data), recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        options.notdef_outline = True
        options.name_IDs = ["*"]  # Includes copyright, license, and license URL.
        options.name_legacy = True
        options.name_languages = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        font.flavor = "woff2"
        # 固定 FontTools/Brotli 版本后，相同输入得到一致的 WOFF2 压缩结果。
        buffer = BytesIO()
        font.save(buffer, reorderTables=True)
        data = buffer.getvalue()
        digest = sha256(data).hexdigest()
        filename = f"ma-shan-zheng-{label}.{digest[:16]}.woff2"
        (OUTPUT / filename).write_bytes(data)
        checked = TTFont(BytesIO(data), recalcTimestamp=False)
        actual_cmap = checked.getBestCmap()
        assert set(actual_cmap) == points, f"Incomplete subset: {label}"
        assert not seen & points, f"Overlapping subset: {label}"
        for point in points:
            assert glyph_signature(source, original_cmap[point]) == glyph_signature(checked, actual_cmap[point]), f"Changed glyph: U+{point:04X}"
            outlines_checked += 1
        seen |= points
        ranges = unicode_ranges(points)
        url = f"/fonts/calligraphy/{filename}"
        css.extend([
            "@font-face {",
            f'  font-family: "{FAMILY}";',
            "  font-style: normal;",
            "  font-weight: 400;",
            "  font-display: swap;",
            f'  src: url("{url}") format("woff2");',
            f"  unicode-range: {ranges};",
            "}",
            "",
        ])
        records.append({"label": label, "url": url, "bytes": len(data), "sha256": digest, "codepoints": len(points), "unicode_range": ranges})
        font.close()
        checked.close()

    assert seen == all_points, "Missing original characters"
    assert outlines_checked == len(all_points)
    CSS.write_text("\n".join(css), encoding="utf-8")
    expected = {Path(record["url"]).name for record in records}
    # 完整验证后，仅清理本生成器专属目录中的旧分片。
    for old in OUTPUT.glob("ma-shan-zheng-*.woff2"):
        if old.name not in expected:
            old.unlink()
    title_points = {ord(character) for character in TITLE}
    title_records = [record for record, (_, points) in zip(records, groups) if title_points & points]
    title_bytes = sum(record["bytes"] for record in title_records)
    original_bytes = SOURCE.stat().st_size
    report = {
        "date": "2026-11-07",
        "generator": "python3 scripts/subset-fonts.py",
        "fonttools_version": fontTools.__version__,
        "source": {"path": str(SOURCE.relative_to(ROOT)), "bytes": original_bytes, "sha256": sha256(SOURCE.read_bytes()).hexdigest(), "mapped_codepoints": len(all_points), "glyphs": source["maxp"].numGlyphs},
        "license": "public/fonts/OFL-MaShanZheng.txt (SIL OFL 1.1, unchanged)",
        "strategy": "Current headline, static theme headings, then disjoint 256-codepoint blocks. No full-font fallback or preload.",
        "validation": {"complete_cmap": seen == all_points, "disjoint_cmap": True, "missing_codepoints": [], "overlapping_codepoints": [], "unchanged_outlines_and_advance_metrics": outlines_checked},
        "subset_count": len(records),
        "total_subset_bytes": sum(record["bytes"] for record in records),
        "css_bytes": CSS.stat().st_size,
        "headline": {"text": TITLE, "font_requests": len(title_records), "font_bytes": title_bytes, "saved_bytes": original_bytes - title_bytes, "reduction_percent": round((1 - title_bytes / original_bytes) * 100, 3), "urls": [record["url"] for record in title_records], "measurement": "Static font-byte calculation from exact Unicode ranges; excludes shared CSS and HTTP headers, not a browser trace."},
        "reference": "https://developer.mozilla.org/en-US/docs/Web/CSS/Reference/At-rules/@font-face/unicode-range",
        "subsets": records,
    }
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    source.close()
    print(json.dumps({"subsets": len(records), "original_bytes": original_bytes, "headline_font_bytes": title_bytes, "complete_cmap": True, "outlines_and_metrics_checked": outlines_checked}, ensure_ascii=False))


if __name__ == "__main__":
    main()
